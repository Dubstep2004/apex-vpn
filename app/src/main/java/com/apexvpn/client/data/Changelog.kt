    /** Изменения, которых пользователь ещё не видел (после обновления приложения). */
    fun unseen(currentCode: Int): List<Release> {
        val seen = Prefs.lastSeenVersionCode
        if (seen == 0) {
            // Первая установка — «Что нового» не показываем
            Prefs.lastSeenVersionCode = currentCode
            return emptyList()
        }
        return releases.filter { it.code in (seen + 1)..currentCode }
    }

    fun markSeen(currentCode: Int) {
        Prefs.lastSeenVersionCode = currentCode
    }
