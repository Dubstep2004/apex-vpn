package com.apexvpn.client.data

/** Вид изменения: метка и её цвет в «Что нового», в релизах GitHub и в docs/CHANGELOG.md. */
enum class ChangeKind(val title: String, val argb: Long, val emoji: String) {
    New("Новое", 0xFF22C55E, "🟢"),
    Improved("Улучшено", 0xFF8B5CF6, "🟣"),
    Changed("Изменено", 0xFF8B5CF6, "🟣"),
    Fixed("Исправлено", 0xFF3B82F6, "🔵"),
    Removed("Удалено", 0xFFEF4444, "🔴"),
}

data class Change(val kind: ChangeKind, val text: String)

/** История версий для экрана «Что нового». Новые версии — сверху. */
data class Release(val version: String, val code: Int, val date: String, val changes: List<Change>)

// Короткие записи для списка ниже. Первая буква — вид изменения
// (scripts/changelog.py читает их же для описаний релизов на GitHub):
private fun n(text: String) = Change(ChangeKind.New, text)      // Новое — зелёная
private fun u(text: String) = Change(ChangeKind.Improved, text) // Улучшено — фиолетовая
private fun c(text: String) = Change(ChangeKind.Changed, text)  // Изменено — фиолетовая
private fun f(text: String) = Change(ChangeKind.Fixed, text)    // Исправлено — синяя
private fun d(text: String) = Change(ChangeKind.Removed, text)  // Удалено — красная

